export function makeFmt(lang: Lang) {
  const loc = lang === 'id' ? 'id-ID' : 'en-US';
  const nf = new Intl.NumberFormat(loc);
  const sep = (s: string) => (lang === 'id' ? s.replace('.', ',') : s);
  return {
    num: (x: number) => nf.format(Math.round(x)),
    pct: (x: number, d = 1) => `${sep((x * 100).toFixed(d))}%`,
    dec: (x: number, d = 2) => sep(x.toFixed(d)),
    compact: (x: number) => {
      if (x >= 1e6) return lang === 'id' ? `${sep((x / 1e6).toFixed(1))} juta` : `${(x / 1e6).toFixed(1)} million`;
      if (x >= 1e3) return lang === 'id' ? `${sep((x / 1e3).toFixed(1))} ribu` : `${(x / 1e3).toFixed(1)}k`;
      return nf.format(Math.round(x));
    },
  };
}
export type Fmt = ReturnType<typeof makeFmt>;

